"""Compile the fixed native audio allowlist from verified local MC outputs."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    clips = {}
    for relative in ('assets/private/minecraft-1.21.1/sounds', 'assets/private/tnt/sounds',
                     'assets/private/building-blocks/sounds', 'assets/private/mechanism-blocks/sounds',
                     'assets/private/elytra-firework/sounds'):
        folder = ROOT / relative
        manifest = json.loads((folder / 'manifest.json').read_text(encoding='utf-8'))
        assert (manifest['format'], manifest['channels'], manifest['sample_rate']) == ('s16le', 2, 44100)
        for clip in manifest['clips']:
            name = clip['name']
            assert re.fullmatch(r'[a-z0-9_]+', name) and clip['file'] == name + '.pcm'
            raw = (folder / clip['file']).read_bytes()
            assert len(raw) == clip['bytes'] and len(raw) % 4 == 0
            assert hashlib.sha256(raw).hexdigest() == clip['sha256']
            spec = (clip['sha256'], len(raw))
            assert name not in clips or clips[name] == spec, 'conflicting audio clip: ' + name
            clips[name] = spec
    lines = ['// Generated by tools/build_audio_catalogue.py from verified local MC audio.', 'constexpr ClipSpec clips[] = {']
    lines.extend(f'    {{"{name}", "{digest}", {size}}},' for name, (digest, size) in clips.items())
    lines += ['#include "construction_sounds.inc"', '#include "mob_sounds.inc"', '#include "potion_sounds.inc"', '};', '']
    (ROOT / 'native/json_bridge/block_audio_catalogue.hpp').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Native original-audio catalogue verified: {len(clips)} clips')


if __name__ == '__main__':
    main()
