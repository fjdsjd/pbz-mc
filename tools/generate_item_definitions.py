"""Generate explicit container definitions from the pinned ID list, not ordinal IDs."""
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ids=json.loads((ROOT/'src/content/upstream_ids.json').read_text(encoding='utf-8'))['items']
assert len(ids)==96 and len(set(ids.values()))==96
entries=[]
for source,id in ids.items():
    name=id.split(':')[1]
    armor=next((slot for suffix,slot in [('helmet','head'),('chestplate','chest'),('leggings','legs'),('boots','feet')] if name.endswith('_'+suffix)),None)
    gear=armor or any(part in name for part in ('sword','pickaxe','spear','mace')) or name in ('shield','bow','trident','flint_and_steel','healing_bottle')
    limit=1 if gear or name in ('boat','totem_of_undying','sheep_machine') else 16 if name=='ender_pearl' else 64
    fields=[f"id='{id}'",f"stack_limit={limit}",f"source='{source}'"]
    if gear: fields.append('instance=true')
    if armor: fields.append(f"equipment_slot='{armor}'")
    if name=='shield': fields.append("preferred_slot='player/offhand'")
    if name=='prize_ticket': fields.append("kind='balance'")
    if name.endswith('_pickaxe'):
        fields.extend(["tool_kind='pickaxe'",f"material='{name.removesuffix('_pickaxe')}'"])
    entries.append(f"  ['{id}']={{{','.join(fields)}}},")
extensions=json.loads((ROOT/'src/content/extension_items.json').read_text(encoding='utf-8'))
assert extensions['schema']==1
seen=set(ids.values())
allowed={'id','stack_limit','source','instance','tool_kind','material','visual_version','equipment_slot'}
for definition in extensions['items']:
    id=definition['id']
    assert re.fullmatch(r'pbzmc:[a-z0-9_]+',id) and id not in seen,'duplicate/invalid extension ID'
    assert set(definition)<=allowed and type(definition['stack_limit']) is int and 1<=definition['stack_limit']<=64
    if definition.get('tool_kind'):
        assert definition['tool_kind'] in ('axe','shovel') and definition['stack_limit']==1 and definition['instance'] is True
        assert definition['material'] in ('wooden','stone','copper','iron','golden','diamond','netherite')
    if definition.get('equipment_slot'):
        assert definition['equipment_slot'] in ('head','chest','legs','feet')
        assert definition['stack_limit']==1 and definition['instance'] is True
    fields=[f'{key}={json.dumps(value,ensure_ascii=False)}' for key,value in definition.items()]
    entries.append(f"  ['{id}']={{{','.join(fields)}}},")
    seen.add(id)
construction=json.loads((ROOT/'src/content/construction_reference.json').read_text(encoding='utf-8'))
potion_reference=json.loads((ROOT/'src/content/potion_reference.json').read_text(encoding='utf8'))
for name in potion_reference['potions']:
    for form in ('potion','splash_potion','lingering_potion'):
        id='pbzmc:'+form+'_'+name
        assert id not in seen
        entries.append(f"  ['{id}']={{id='{id}',stack_limit=1,source='minecraft:{form}',visual_version='26.3'}},")
        seen.add(id)
for name,limit in [('milk_bucket',1),('glass_bottle',64)]:
    id='pbzmc:'+name
    if id not in seen:
        entries.append(f"  ['{id}']={{id='{id}',stack_limit={limit},source='minecraft:{name}',visual_version='26.3'}},")
        seen.add(id)
def lua(value):
    if isinstance(value,dict):return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    if isinstance(value,str):
        if value in ('true','false'):return value
        if value.isdigit():return value
    return json.dumps(value,ensure_ascii=False)
profiles=[]
for defaults,states in construction['profiles']:
    key=','.join(defaults[k] for k in sorted(defaults))
    collision,outline,light,opaque,conductor=states[key]
    shape=construction['shapes'][collision]
    profiles.append(dict(defaults=defaults,full=(shape==[[0,0,0,1,1,1]]),solid=bool(shape),
                         opaque=opaque,conductor=conductor,light=max(state[2] for state in states.values())))
rows=[]
for name,cls,profile,hardness,resistance,correct,tools,tier,push,sound in construction['blocks']:
    id='pbzmc:'+name
    if id not in seen:
        entries.append(f"  ['{id}']={{id='{id}',stack_limit=64,source='minecraft:{name}'}},")
        seen.add(id)
    rows.append('  '+lua([name,cls,profile+1,hardness,resistance,correct,tools,tier,push,sound])+',')
generated='-- Generated from the vanilla 26.3 creative tabs and block states.\nreturn {profiles='+lua(profiles)+',rows={\n'+'\n'.join(rows)+'\n}}\n'
(ROOT/'src/content/construction_registry.lua').write_text(generated,encoding='utf8')
text="""-- Generated by tools/generate_item_definitions.py; named IDs stay explicit.
-- Container/equipment metadata only: this is not a claim that every behaviour or
-- model is implemented. Custom life/bottle upgrades and clovers retain 64 stacks;
-- healing bottle is permanent, sheep-machine deployment is a single item.
-- Local additions come from extension_items.json; upstream enum mapping stays pinned.
local entries={
"""+'\n'.join(entries)+"\n}\nreturn {get=function(id) return entries[id] end,all=function() return entries end}\n"
(ROOT/'src/content/items.lua').write_text(text,encoding='utf-8')
print(f'Generated {len(entries)} explicit item definitions')
