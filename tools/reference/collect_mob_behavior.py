"""Retain the vanilla numeric goal parameters, not original media or code."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT=Path(__file__).resolve().parents[2]
COMMIT='15701fa9c13923f12662984c32c124327e40e3d3'
CACHE=ROOT/'research/private/mob-behavior'/COMMIT
ALIASES={'zombified_piglin':'zombie_pigman','zombie_villager':'zombie_villager_v2',
 'giant':'zombie','illusioner':'skeleton','killer_bunny':'rabbit','trader_llama':'llama','villager':'villager_v2',
 'cod':'fish','evoker':'evocation_illager','tropical_fish':'tropicalfish'}
KINDS=('health','movement','attack','behavior.melee_attack','behavior.delayed_attack',
 'behavior.ranged_attack','behavior.swell','explode','behavior.sonic_boom',
 'behavior.swoop_attack','behavior.charge_attack','behavior.leap_at_target','behavior.ram_attack')
def fetch(name):
    alias=ALIASES.get(name,name)
    url=f'https://raw.githubusercontent.com/Mojang/bedrock-samples/{COMMIT}/behavior_pack/entities/{alias}.json'
    p=CACHE/(alias+'.json');p.parent.mkdir(parents=True,exist_ok=True)
    if not p.exists():
        try:
            with urllib.request.urlopen(url,timeout=25) as response:p.write_bytes(response.read())
        except Exception as e:return name,{'error':str(e),'url':url}
    raw=p.read_bytes()
    data=json.loads(re.sub(r'//[^\r\n]*','',raw.decode('utf-8-sig')))['minecraft:entity']
    groups={'base':data.get('components',{}),**data.get('component_groups',{})}
    selected={k:{goal.removeprefix('minecraft:'):v for goal,v in group.items()
      if goal.removeprefix('minecraft:') in KINDS or goal.startswith('minecraft:behavior.') and any(x in goal for x in ('attack','follow_owner','teleport','swell'))} for k,group in groups.items()}
    return name,{'url':url,'sha256':hashlib.sha256(raw).hexdigest(),'groups':{k:v for k,v in selected.items() if v}}

if __name__=='__main__':
    names=[]
    for f in ('undead','summon_mobs'):
        names+=re.findall(r"(?:mob|species)\('([^']+)'",(ROOT/f'src/content/{f}.lua').read_text('utf8'))
    with ThreadPoolExecutor(max_workers=6) as pool:rows=dict(pool.map(fetch,names))
    out=ROOT/'src/content/mob_behavior_reference.json'
    out.write_text(json.dumps({'source_commit':COMMIT,'mobs':rows},ensure_ascii=False,indent=2)+'\n','utf8')
    def lua(v):
        if isinstance(v,dict):return '{'+','.join('['+json.dumps(k)+']='+lua(x) for k,x in v.items())+'}'
        if isinstance(v,list):return '{'+','.join(map(lua,v))+'}'
        return json.dumps(v)
    (ROOT/'src/content/mob_behavior_reference.lua').write_text('-- Generated by tools/reference/collect_mob_behavior.py; pinned Bedrock numeric goals.\nreturn '+lua(rows)+'\n','utf8')
    print(json.dumps({'rows':len(rows),'missing':{k:v for k,v in rows.items() if 'error' in v}}))
